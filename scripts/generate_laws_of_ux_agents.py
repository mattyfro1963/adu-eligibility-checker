def _bullets(items: object) -> list[str]:
    return [f"- {item}" for item in list(items)]


def render_agent(law: dict[str, object]) -> str:
    slug = str(law["slug"])
    title = str(law["title"])
    url = str(law["url"])
    principle = str(law["principle"])
    invoke_short = str(law["invoke_short"])
    finding = FINDING_TEMPLATE.format(title=title)

    lines = [
        "---",
        f"name: ux-{slug}",
        "description: >-",
        f"  Laws of UX — {title}: {principle} Invoke for Envirostar React/Vite UI when {invoke_short}.",
        "model: composer-2.5",
        "autoApproveTools: false",
        "---",
        "",
        f"# {title} UX agent",
        "",
        "**Orchestrator:** `@.cursor/agents/laws-of-ux-orchestrator.md`",
        f"**Source:** [{title}]({url}) · [Laws of UX](https://lawsofux.com/)",
        "",
        "## Principle",
        "",
        principle,
        "",
        "## When to invoke",
        "",
        "Run this agent only for the product triggers below. Do not start from a generic \"UX review\" unless the orchestrator selected this law.",
        "",
        "### Product triggers",
        "",
        *_bullets(law["triggers"]),
        "",
        "## How to apply",
        "",
        "Work **observe → diagnose → prescribe**. Cite a real path. Recommend one concrete change per finding.",
        "",
        f"1. **Observe:** {law['observe']}",
        f"2. **Diagnose against this law:** {law['diagnose']}",
        f"3. **Prescribe:** {law['prescribe']}",
        "",
        "### What not to do",
        "",
        *_bullets(law["do_not"]),
        "",
        "## Envirostar surfaces",
        "",
        "Bind findings to these routes/components when they are in scope. If a named file is not in the diff, say so and review the closest live surface instead of inventing one.",
        "",
        *_bullets(law["surfaces"]),
        "",
        "## Review checklist",
        "",
    ]
    for item in list(law["checklist"]):
        lines.append(f"- [ ] {item}")
    lines.extend(
        [
            "",
            "## Finding format",
            "",
            "Emit one block per finding (one primary law). Severity: blocker | major | minor | nit.",
            "",
            finding,
            "",
            "## Anti-patterns",
            "",
            *_bullets(law["anti_patterns"]),
            "",
            "## Handoff",
            "",
            str(law["handoff"]),
            "",
        ]
    )
    return "\n".join(lines)


