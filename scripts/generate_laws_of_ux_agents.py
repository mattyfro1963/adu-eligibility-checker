def main() -> None:
    AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    for law in LAWS:
        path = AGENTS_DIR / f"{law['slug']}.md"
        path.write_text(render_agent(law), encoding="utf-8")
    readme = AGENTS_DIR / "README.md"
    readme.write_text(render_readme(), encoding="utf-8")
    print(f"Wrote {len(LAWS)} agents + README to {AGENTS_DIR}")


if __name__ == "__main__":
    main()
